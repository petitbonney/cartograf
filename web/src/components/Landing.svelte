<script lang="ts">
  import { SAMPLE_FILE, store } from '../lib/store.svelte'

  let input: HTMLInputElement

  function onPick(e: Event) {
    const file = (e.currentTarget as HTMLInputElement).files?.[0]
    if (file) store.loadFile(file)
  }
</script>

<div class="page landing">
  <h1>Map framework usage across your repositories</h1>
  <p class="lead">
    Open the <code>cartography.yaml</code> (or <code>.json</code>) written by cartograf to explore frameworks,
    versions, outdated repositories and the review queue.
  </p>

  <button class="drop" onclick={() => input.click()}>
    <svg width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" aria-hidden="true">
      <path d="M12 16V4m0 0-4 4m4-4 4 4M4 16v2a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-2" stroke-linecap="round" stroke-linejoin="round" />
    </svg>
    <strong>Choose a file</strong>
    <span class="muted">or drop it anywhere on this page</span>
  </button>
  <input bind:this={input} type="file" accept=".yaml,.yml,.json" hidden onchange={onPick} />

  <p class="privacy">The file is read in your browser. It is not uploaded anywhere.</p>

  <div class="alt">
    <button class="btn" onclick={() => store.loadUrl(`./${SAMPLE_FILE}`, SAMPLE_FILE)}>Try the sample data</button>
    <span class="muted">Fictional repositories, generated by the real analysis.</span>
  </div>

  <details>
    <summary>Publishing your data with this page</summary>
    <p>
      Put <code>cartography.yaml</code> next to <code>index.html</code> and set <code>config.json</code> to
      <code>{'{"data": "cartography.yaml"}'}</code>: the page then opens it on load. Only do this where the site is
      access-controlled: the file names internal repositories, the GitLab URL and the token’s user.
    </p>
  </details>
</div>

